# Python Type Hinting Operators
# x: type  # Type hint for variable x
# x: Optional[type]  # Type hint for variable x that can be of type type or None
# x: Union[type1, type2]  # Type hint for variable x that can be of type type1 or type2
# x: List[type]  # Type hint for a list of type type
# x: Dict[key_type, value_type]  # Type hint for a dictionary with key_type and value_type
# x: Tuple[type1, type2]  # Type hint for a tuple with type1 and type2
# x: Any  # Type hint for any type
# x: Literal[value]  # Type hint for a specific value
# x: Callable[[arg_type], return_type]  # Type hint for a callable that takes arg_type and returns return_type
# x: Type[type]  # Type hint for a type object
# x: ClassVar[type]  # Type hint for a class variable
# x: Final[type]  # Type hint for a final variable that cannot be reassigned
# x: LiteralString  # Type hint for a string literal
# x: TypeGuard[type]  # Type hint for a type guard function
# x: Self  # Type hint for a method that returns an instance of the class
# x: Protocol  # Type hint for a protocol that defines a set of methods and attributes
# x: TypedDict  # Type hint for a dictionary with a fixed set of keys and value types
# x: TypedList  # Type hint for a list with a fixed set of types
# x: TypedTuple  # Type hint for a tuple with a fixed set of types
